#!/usr/bin/env python3
"""
Render today's motivation card as a shareable PNG poster.

Reads data/daily.json (generated by generator/daily.py), fetches the headline
image, and draws a 1080x1350 (portrait 9:12, Telegram-friendly) card with the
quote, author, theme and date. Output: data/poster_<date>.png

Usage:
  venv/bin/python generator/render_poster.py [--date YYYY-MM-DD] [--out PATH]
"""
import argparse, json, os, sys, textwrap, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DAILY = ROOT / "data" / "daily.json"

# --- config (tweak freely) ---------------------------------------------
SIZE = (1080, 1350)               # portrait 4:5 -> nice for Telegram
ACCENT = (233, 196, 106)          # gold
TEXT = (244, 246, 250)            # near-white
MUTED = (178, 184, 200)
FONT_DIR = "/usr/share/fonts/truetype"
ASSETS = ROOT / "assets" / "fonts"   # bundled OFL fonts (both cover Latin + Cyrillic)
# candidate lists: first existing wins, system fonts are the fallback
F_QUOTE = [str(ASSETS / "PlayfairDisplay-Italic[wght].ttf"), f"{FONT_DIR}/liberation/LiberationSerif-Italic.ttf", f"{FONT_DIR}/freefont/FreeSerifItalic.ttf", f"{FONT_DIR}/dejavu/DejaVuSerif.ttf"]
F_UI = [str(ASSETS / "Manrope[wght].ttf"), f"{FONT_DIR}/dejavu/DejaVuSans.ttf", f"{FONT_DIR}/liberation/LiberationSans-Regular.ttf"]

MARGIN = 60
CARD_PAD = 50                      # inner padding of the glass card
CARD_MAX_TOP = 470                 # card never grows above this y (keeps the photo visible)
CARD_BOTTOM = SIZE[1] - 88         # card bottom edge (footer lives below it)


def font(cands, size, weight=None):
    """Load the first available font; for variable fonts pick the weight axis (400-900 etc.)."""
    from PIL import ImageFont
    for c in cands:
        if os.path.exists(c):
            f = ImageFont.truetype(c, size)
            if weight is not None:
                try:
                    f.set_variation_by_axes([weight])
                except Exception:
                    pass  # static font: weight is baked in
            return f
    return ImageFont.load_default()


def fetch_image(url, dst):
    """Download the card's background photo into data/_img cache."""
    Path(dst).parent.mkdir(parents=True, exist_ok=True)
    if os.path.exists(dst):
        return dst
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (motivation-poster/1.0)"})
    tmp = f"{dst}.part"  # download then rename, so a failed fetch never leaves a corrupt cache file
    with urllib.request.urlopen(req, timeout=40) as r, open(tmp, "wb") as f:
        f.write(r.read())
    os.replace(tmp, dst)
    return dst


def wrap(text, font, max_w, draw):
    """word-wrap using font metrics"""
    words = text.split()
    lines, cur = [], ""
    for w in words:
        test = (cur + " " + w).strip()
        if draw.textlength(test, font=font) <= max_w:
            cur = test
        else:
            if cur:
                lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines or [text]


def outline(img, box, radius, rgba, width=2):
    """Alpha-correct outline (drawing RGBA straight onto the image would not blend)."""
    from PIL import Image, ImageDraw
    ov = Image.new("RGBA", img.size, (0, 0, 0, 0))
    ImageDraw.Draw(ov).rounded_rectangle(box, radius=radius, outline=rgba, width=width)
    return Image.alpha_composite(img, ov)


def glass_pill(img, box, border_rgba):
    """Frosted capsule: blurred photo underneath, dark tint, thin border."""
    from PIL import Image, ImageDraw, ImageFilter
    box = tuple(int(v) for v in box)
    g = img.crop(box).filter(ImageFilter.GaussianBlur(14))
    g = Image.alpha_composite(g, Image.new("RGBA", g.size, (12, 15, 24, 120)))
    m = Image.new("L", g.size, 0)
    r = g.height // 2
    ImageDraw.Draw(m).rounded_rectangle((0, 0, g.width - 1, g.height - 1), radius=r, fill=255)
    img.paste(g, (box[0], box[1]), m)
    return outline(img, box, r, border_rgba)


def spaced(draw, xy, text, fnt, fill, tracking=3, anchor_center=False, anchor_right=False):
    """Draw letter-spaced text (PIL has no tracking). Returns the drawn width."""
    widths = [draw.textlength(ch, font=fnt) for ch in text]
    total = sum(widths) + tracking * max(len(text) - 1, 0)
    x, y = xy
    if anchor_center:
        x -= total / 2
    elif anchor_right:
        x -= total
    for ch, w in zip(text, widths):
        draw.text((x, y), ch, font=fnt, fill=fill)
        x += w + tracking
    return total


def render(entry, out_path):
    from PIL import Image, ImageDraw, ImageFilter

    W, H = SIZE
    # --- full-bleed photo (cover crop) ---
    base = Image.new("RGB", SIZE, (17, 20, 30))
    try:
        img_path = fetch_image(entry["image"], ROOT / "data" / "_img" / f"{entry['date']}.jpg")
        photo = Image.open(img_path).convert("RGB")
        scale = max(W / photo.width, H / photo.height)
        nw, nh = round(photo.width * scale), round(photo.height * scale)
        photo = photo.resize((nw, nh), Image.LANCZOS)
        left, top = (nw - W) // 2, int((nh - H) * 0.35)   # bias crop upward: skies/horizons stay in frame
        base = photo.crop((left, top, left + W, top + H))
    except Exception as e:
        print(f"[render] photo fallback: {e}", file=sys.stderr)

    # --- gradient: clear at top, deep dark toward the text area ---
    grad = Image.new("L", (1, H))
    for y in range(H):
        t = max(0.0, (y - H * 0.18) / (H * 0.82))
        grad.putpixel((0, y), int(235 * (t ** 1.35)))
    grad = grad.resize((W, H))
    shade = Image.new("RGB", SIZE, (9, 11, 18))
    img = Image.composite(shade, base, grad)
    img = img.convert("RGBA")
    draw = ImageDraw.Draw(img)

    quote_text = entry.get(entry.get("lang", "en")) or entry["en"]
    author = entry.get("author", "")

    # --- fit quote inside the glass card ---
    inner_w = W - 2 * MARGIN - 2 * CARD_PAD
    author_block = 56                              # author line (no rule)
    max_text_h = CARD_BOTTOM - CARD_MAX_TOP - 2 * CARD_PAD - author_block
    # the quote sits between typographic quotes (RU uses guillemets); marks are drawn gold
    q_open, q_close = ("\u00ab", "\u00bb") if entry.get("lang") == "ru" else ("\u201c", "\u201d")
    quote_text = f"{q_open}{quote_text.strip()}{q_close}"
    chosen = None
    for size_px in range(76, 29, -2):
        qf = font(F_QUOTE, size_px, 500)
        lh = int(size_px * 1.28)
        lines = wrap(quote_text, qf, inner_w, draw)
        if len(lines) * lh <= max_text_h:
            chosen = (qf, lines, lh)
            break
        chosen = (qf, lines, lh)
    qf, lines, lh = chosen
    text_h = len(lines) * lh
    card_h = 2 * CARD_PAD + text_h + author_block
    card_top = max(CARD_MAX_TOP, CARD_BOTTOM - card_h)
    card_top = CARD_BOTTOM - card_h if card_h > CARD_BOTTOM - CARD_MAX_TOP else card_top
    card = (MARGIN, card_top, W - MARGIN, CARD_BOTTOM)

    # --- frosted glass: blurred photo under a dark tint, rounded corners, hairline border ---
    glass = img.crop(card).filter(ImageFilter.GaussianBlur(26))
    tint = Image.new("RGBA", glass.size, (12, 15, 24, 150))
    glass = Image.alpha_composite(glass, tint)
    mask = Image.new("L", glass.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, glass.width - 1, glass.height - 1), radius=44, fill=255)
    img.paste(glass, (card[0], card[1]), mask)
    img = outline(img, card, 44, (255, 255, 255, 46))
    draw = ImageDraw.Draw(img)

    # --- top bar: theme pill (left) + date pill (right) ---
    tf = font(F_UI, 26, 700)
    theme = entry.get("theme", "").upper()
    tw = sum(draw.textlength(c, font=tf) for c in theme) + 4 * (len(theme) - 1)
    pill = (MARGIN, 58, MARGIN + tw + 56, 120)
    img = glass_pill(img, pill, ACCENT + (170,))
    df = font(F_UI, 28, 500)
    dt = entry["date"]
    dw = draw.textlength(dt, font=df)
    dpill = (W - MARGIN - dw - 56, 58, W - MARGIN, 120)
    img = glass_pill(img, dpill, (255, 255, 255, 60))
    draw = ImageDraw.Draw(img)
    spaced(draw, (pill[0] + 28, pill[1] + 15), theme, tf, ACCENT, tracking=4)
    draw.text((dpill[0] + 28, dpill[1] + 13), dt, font=df, fill=TEXT)

    # --- quote lines (opening/closing marks in gold), then author ---
    x0 = card[0] + CARD_PAD
    y = card[1] + CARD_PAD
    last = len(lines) - 1
    for i, ln in enumerate(lines):
        x = x0
        if i == 0 and ln.startswith(q_open):
            draw.text((x, y), q_open, font=qf, fill=ACCENT)
            x += draw.textlength(q_open, font=qf)
            ln = ln[len(q_open):]
        if i == last and ln.endswith(q_close):
            body = ln[:-len(q_close)]
            draw.text((x, y), body, font=qf, fill=TEXT)
            draw.text((x + draw.textlength(body, font=qf), y), q_close, font=qf, fill=ACCENT)
        else:
            draw.text((x, y), ln, font=qf, fill=TEXT)
        y += lh
    y += 14
    right = card[2] - CARD_PAD
    af = font(F_UI, 32, 800)
    spaced(draw, (right, y), author.upper(), af, ACCENT, tracking=3, anchor_right=True)

    # --- footer (shrinks to fit so long photographer names are never clipped) ---
    foot = "Daily Motivation Quote"
    if entry.get("photo", {}).get("name"):
        foot += f" \u00b7 Photo: {entry['photo']['name']} / Unsplash"
    fsize = 26
    ff = font(F_UI, fsize, 500)
    while draw.textlength(foot, font=ff) > W - 2 * MARGIN and fsize > 16:
        fsize -= 1
        ff = font(F_UI, fsize, 500)
    draw.text(((W - draw.textlength(foot, font=ff)) / 2, H - 62), foot, font=ff, fill=MUTED)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    img.convert("RGB").save(out_path, "PNG")
    print(out_path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--lang", default="en", choices=["en", "ru"])
    ap.add_argument("--daily", default=str(DAILY), help="path to a daily.json (default: data/daily.json)")
    args = ap.parse_args()

    with open(args.daily, encoding="utf-8") as f:
        entry = json.load(f)
    if args.date and entry.get("date") != args.date:
        sys.exit(f"[render] {args.daily} is for {entry.get('date')}, not {args.date}")
    entry["lang"] = args.lang
    date = entry.get("date", "today")
    out = args.out or str(ROOT / "data" / f"poster_{date}.png")
    render(entry, out)


if __name__ == "__main__":
    main()